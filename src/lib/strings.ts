/** The active dictionary for a locale. Both dicts share the exact key
 * tree (compile-time enforced by `zh: typeof en`). */
export function stringsFor(locale: Locale): typeof en {
  return locale === "zh-CN" ? zh : en;
}

export type Strings = typeof en;

/** The default (English) dictionary — for tests and non-React
 * consumers that do not need reactivity. */
export const strings = en;
